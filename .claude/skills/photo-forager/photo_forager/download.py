"""Download chosen images and write a license manifest + credits file.

The manifest is the safety record: every downloaded file is logged with its
source, license, and whether a credit is required. CREDITS.md surfaces the
exact attribution string for any file that needs one (only Unsplash, given the
default sources), so you can paste it under a post or into a content footer.
"""

import os
import sys
import json
import datetime

from photo_forager.sources import http_get, USER_AGENT, UNSPLASH_KEY_ENV


def _safe_name(idx, r):
    base = f"{idx:02d}_{r.source}_{r.id}".replace("/", "-")
    return base + ".jpg"


def _trigger_unsplash_download(r):
    """Ping Unsplash's download_location endpoint (required by their API ToS)."""
    loc = (r.extra or {}).get("download_location")
    key = os.environ.get(UNSPLASH_KEY_ENV)
    if not loc or not key:
        return
    try:
        http_get(loc, headers={"Authorization": f"Client-ID {key}"}, timeout=15)
    except Exception:
        pass  # best-effort; never block the actual image download


def _fetch_image(r):
    """Return image bytes, falling back to a Rawpixel alt URL if needed."""
    try:
        data = http_get(r.full_url, headers={"Accept": "image/*"}, timeout=30)
        if data and len(data) > 1024:
            return data
    except Exception:
        pass
    fallback = (r.extra or {}).get("fallback_url")
    if fallback and fallback != r.full_url:
        try:
            return http_get(fallback, headers={"Accept": "image/*"}, timeout=30)
        except Exception:
            return None
    return None


def download_results(results, out_dir):
    """Download every result in `results` into out_dir. Returns (manifest, errors)."""
    os.makedirs(out_dir, exist_ok=True)
    manifest = []
    errors = []
    for i, r in enumerate(results, 1):
        if r.source == "unsplash":
            _trigger_unsplash_download(r)
        data = _fetch_image(r)
        if not data:
            errors.append(f"{r.source}:{r.id} — download failed")
            continue
        fname = _safe_name(i, r)
        with open(os.path.join(out_dir, fname), "wb") as fh:
            fh.write(data)
        manifest.append({
            "file": fname,
            "source": r.source,
            "id": r.id,
            "title": r.title,
            "license": r.license_name,
            "attribution_required": r.attribution_required,
            "attribution_text": r.attribution_text,
            "photographer": r.photographer,
            "source_page": r.source_page,
            "bytes": len(data),
        })
    _write_manifest(out_dir, manifest)
    _write_credits(out_dir, manifest)
    return manifest, errors


def _write_manifest(out_dir, manifest):
    with open(os.path.join(out_dir, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)


def _write_credits(out_dir, manifest):
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    need = [m for m in manifest if m["attribution_required"]]
    free = [m for m in manifest if not m["attribution_required"]]
    lines = [
        "# Image Credits",
        "",
        f"_Generated by photo-forager on {stamp}._",
        "",
        "## ⚠️ Attribution required — paste this credit where the image appears",
        "",
    ]
    if need:
        for m in need:
            lines.append(f"- **{m['file']}** — {m['attribution_text']}")
    else:
        lines.append("None. Every image below is attribution-free "
                     "(CC0 / Public Domain / Pexels License).")
    lines += [
        "",
        "## ✓ Attribution-free — no credit needed",
        "",
    ]
    for m in free:
        page = f" — {m['source_page']}" if m["source_page"] else ""
        lines.append(f"- {m['file']} — {m['license']}{page}")
    lines.append("")
    with open(os.path.join(out_dir, "CREDITS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def print_download_summary(manifest, errors, out_dir):
    print(f"\nDownloaded {len(manifest)} image(s) -> {out_dir}", file=sys.stderr)
    need = [m for m in manifest if m["attribution_required"]]
    if need:
        print(f"  ⚠️  {len(need)} need a credit — see {out_dir}/CREDITS.md", file=sys.stderr)
    else:
        print("  ✓ all attribution-free (no credit needed)", file=sys.stderr)
    print(f"  manifest: {out_dir}/manifest.json", file=sys.stderr)
    for e in errors:
        print(f"  ! {e}", file=sys.stderr)
